import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
const root=path.resolve(import.meta.dirname,'..');
const filename='20261026140335_employee_managed_username_access.sql';
const sql=fs.readFileSync(path.join(root,'supabase/migrations',filename),'utf8');
const uncommented=sql.replace(/--[^\n]*/g,'');
assert.match(uncommented,/^\s*begin;[\s\S]*commit;\s*$/i);
assert.match(sql,/create schema employee_login;/);
for(const table of ['owners','aliases','throttles','audit'])assert.ok(sql.includes(`alter table employee_login.${table} enable row level security;`));
assert.match(sql,/revoke all on all tables in schema employee_login from public,anon,authenticated,service_role;/);
assert.match(sql,/revoke all on all functions in schema employee_login from public,anon,authenticated,service_role;/);
assert.match(sql,/current_setting\('role',true\) is distinct from 'service_role'/);
assert.match(sql,/user_id uuid not null unique references auth\.users\(id\)/);
assert.match(sql,/code_hash text check\(code_hash collate "C" ~ '\^\[a-f0-9\]\{64\}\$'\)/);
assert.match(sql,/v_expires:=clock_timestamp\(\)\+interval '10 minutes'/);
assert.match(sql,/v_alias\.state in \('processing','failed'\)/);
assert.match(sql,/for update skip locked/);
assert.match(sql,/create function public\.get_employee_login_access\(\)/);
assert.match(sql,/v_uid uuid:=auth\.uid\(\)/);
assert.match(sql,/grant execute on function public\.get_employee_login_access\(\) to authenticated;/);
assert.doesNotMatch(uncommented,/\b(?:insert\s+into|update|delete\s+from)\s+(?:auth\.|public\.)/i,'No Auth or existing business records may change');
assert.doesNotMatch(uncommented,/\b(?:insert\s+into|update|delete\s+from)\s+employee_login\.owners/i,'No owner membership is seeded');
assert.doesNotMatch(uncommented,/\binsert\s+into\s+employee_login\.aliases/i,'No alias is seeded');
assert.doesNotMatch(uncommented,/\b(?:create\s+or\s+replace|drop)\s+(?:function|policy|table)/i,'No existing business helper/policy/table may be replaced');
assert.doesNotMatch(uncommented,/user_metadata|raw_user_meta_data|encrypted_password|password_hash/i,'No user-controlled authorization or password storage');
const audit=sql.match(/create table employee_login\.audit \(([\s\S]*?)\n\);/)[1];
assert.doesNotMatch(audit.replace('confirm_email boolean not null default false',''),/username|email|ip_address|password|code_hash|token|detail|jsonb/i,'Audit contains fixed fields, not secret-bearing free-form payloads');
const publicFunctions=[...sql.matchAll(/create function public\.(\w+)\(/g)].map(m=>m[1]);
assert.equal(publicFunctions.length,11);
assert.equal(publicFunctions.filter(n=>n==='get_employee_login_access').length,1);
assert.ok(publicFunctions.every(n=>n==='get_employee_login_access'||n.startsWith('employee_login_')));
for(const body of sql.matchAll(/create function public\.employee_login_\w+\([^]*?\$\$;(?=\s*(?:--|create|revoke|grant|comment|commit))/g))assert.match(body[0],/perform employee_login\.require_service\(\);/);
console.log('PASS: private managed-login schema, service-only credential APIs, no identities/business grants/password storage seeded or modified.');
